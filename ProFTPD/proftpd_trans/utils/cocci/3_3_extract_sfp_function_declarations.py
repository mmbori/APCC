def generate_cocci_script(target_functions):
    """Generate complete Coccinelle script"""
    lines = [generate_header()]
    
    # Generate rules for each function
    for i, func in enumerate(target_functions):
        if func in ("NULL", "0"):
            continue
        lines.append(generate_cocci_rules(func))
        if i < len(target_functions) - 1:
            lines.append("")
    
    return '\n'.join(lines)

def main():
    # Parse command line arguments
    if len(sys.argv) != 3:
        print("Usage: python3 2_4_extract_definition.py <json_file> <output_cocci>")
        print()
        print("Arguments:")
        print("  json_file    : JSON file containing function data (e.g., filled_parsing.json)")
        print("  output_cocci : Output Coccinelle script file (e.g., extract_decl.cocci)")
        print()
        print("Example:")
        print("  python3 2_4_extract_definition.py filled_parsing.json extract_decl.cocci")
        print()
        print("To run and extract declarations:")
        print("  spatch --sp-file extract_decl.cocci --dir ../ 2>/dev/null > declarations.txt")
        print("  (or with --in-place to modify files)")
        print("  spatch --sp-file extract_decl.cocci --dir ../ --in-place 2>/dev/null > declarations.txt")
        sys.exit(1)
    
    json_file = sys.argv[1]
    output_cocci = sys.argv[2]
    
    # Check if input files exist
    if not os.path.exists(json_file):
        print(f"Error: JSON file not found: {json_file}", file=sys.stderr)
        sys.exit(1)
    
    # Load data
    print(f"Loading target functions from {json_file}...", file=sys.stderr)
    target_functions = load_target_functions(json_file)
    
    if not target_functions:
        print(f"Error: No valid functions found in {json_file}", file=sys.stderr)
        sys.exit(1)
    
    print(f"Found {len(target_functions)} unique target functions", file=sys.stderr)
    
    # Generate Coccinelle script
    print(f"Generating Coccinelle script with rules for {len(target_functions)} functions...", file=sys.stderr)
    cocci_script = generate_cocci_script(target_functions)
    
    # Write to output file
    with open(output_cocci, 'w', encoding='utf-8') as f:
        f.write(cocci_script)
    
    print(f"Coccinelle script written to {output_cocci}", file=sys.stderr)
    print(f"", file=sys.stderr)
    print(f"[SUCCESS] Script generation complete!", file=sys.stderr)
    print(f"", file=sys.stderr)
    print(f"To extract declarations only (no diff):", file=sys.stderr)
    print(f"  spatch --sp-file {output_cocci} --dir <source_dir> 2>/dev/null > declarations.txt", file=sys.stderr)
    print(f"", file=sys.stderr)
    print(f"To modify files AND extract declarations:", file=sys.stderr)
    print(f"  spatch --sp-file {output_cocci} --dir <source_dir> --in-place 2>/dev/null > declarations.txt", file=sys.stderr)

if __name__ == '__main__':
    main()