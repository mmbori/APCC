def clean_function_signature(signature):
    '''Clean up function signature formatting'''
    if not signature:
        return signature
    
    # Normalize all whitespace
    signature = re.sub(r'\\s+', ' ', signature.strip())
    
    # Remove all spaces around asterisks first
    signature = re.sub(r'\\s*\\*\\s*', '*', signature)
    
    # Add space before asterisk groups
    signature = re.sub(r'(\\w)(\\*+)', r'\\1 \\2', signature)
    
    # Clean up double spaces
    signature = re.sub(r'\\s+', ' ', signature)
    
    return signature.strip()

def extract_and_print_signature(signature, func_name):
    '''Extract and print function signature to stdout'''
    clean_signature = clean_function_signature(signature)
    # Only print to stdout (will be captured by redirection)
    print(f"{clean_signature}")
    # Debug info goes to stderr
    print(f"[EXTRACTED] {func_name}: {clean_signature}", file=sys.stderr)

